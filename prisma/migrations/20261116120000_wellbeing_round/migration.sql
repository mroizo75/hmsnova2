CREATE TABLE `WellbeingRound` (
  `id` VARCHAR(191) NOT NULL,
  `tenantId` VARCHAR(191) NOT NULL,
  `formTemplateId` VARCHAR(191) NOT NULL,
  `title` VARCHAR(191) NOT NULL,
  `message` TEXT NULL,
  `dueDate` DATETIME(3) NULL,
  `status` ENUM('ACTIVE','CLOSED') NOT NULL DEFAULT 'ACTIVE',
  `createdById` VARCHAR(191) NOT NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `closedAt` DATETIME(3) NULL,
  PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `WellbeingRoundRecipient` (
  `id` VARCHAR(191) NOT NULL,
  `roundId` VARCHAR(191) NOT NULL,
  `userId` VARCHAR(191) NOT NULL,
  `status` ENUM('PENDING','ANSWERED') NOT NULL DEFAULT 'PENDING',
  `answeredAt` DATETIME(3) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE INDEX `WellbeingRound_tenantId_status_idx` ON `WellbeingRound`(`tenantId`, `status`);
CREATE INDEX `WellbeingRound_formTemplateId_idx` ON `WellbeingRound`(`formTemplateId`);
CREATE UNIQUE INDEX `WellbeingRoundRecipient_roundId_userId_key` ON `WellbeingRoundRecipient`(`roundId`, `userId`);
