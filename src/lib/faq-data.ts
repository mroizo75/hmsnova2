// Funksjon for å hente relevante FAQs basert på side
export function getFAQsForPage(pageType: string): FAQItem[] {
  switch (pageType) {
    case 'home':
      return [
        ...faqDatabase.general,
        ...faqDatabase.comparison.slice(0, 2),
        {
          question: 'Må vi skrive HMS-håndboken selv?',
          answer:
            'Nei. KS-, HMS- og personalhåndbok kommer med standardtekst, i tråd med ISO 9001, ISO 45001 og internkontrollforskriften. Veiviseren henter lover og forskrifter for bransjen og legger inn standardrutiner. Dere endrer det som er spesielt for egen bedrift.',
        },
        {
          question: 'Kan vi ta med HMS-arbeidet vi allerede har laget?',
          answer:
            'Ja. Risikovurdering kan lastes opp som PDF, Word eller Excel. Du ser utkastet og bekrefter punktene før de lagres. Ansatte importeres fra CSV eller Excel, og personaldata kan hentes fra PowerOffice. Egne dokumenter lastes opp i dokumentstyringen. Det som mangler, dekkes av standardteksten. Trenger dere hjelp med hele flyttingen, tar dere kontakt. Omfang og pris avtales før vi starter.',
        },
      ];
    case 'pricing':
      return [
        faqDatabase.general[1], // Hva koster
        faqDatabase.comparison[1], // vs Excel
        faqDatabase.implementation[2], // Oppsigelse
        faqDatabase.general[4], // Gratis test
      ];
    case 'comparison':
      return faqDatabase.comparison;
    case 'industry-bygg':
      return [faqDatabase.industry[0], ...faqDatabase.general.slice(0, 3)];
    case 'industry-helse':
      return [faqDatabase.industry[1], ...faqDatabase.general.slice(0, 3)];
    case 'industry-transport':
      return [faqDatabase.industry[2], ...faqDatabase.general.slice(0, 3)];
    case 'technical':
      return faqDatabase.technical;
    case 'implementation':
      return faqDatabase.implementation;
    default:
      return faqDatabase.general;
  }
}

// Hent FAQs basert på kategori
export function getFAQsByCategory(category: keyof typeof faqDatabase): FAQItem[] {
  return faqDatabase[category] || [];
}

// Hent alle FAQs (for dedikert FAQ-side)
export function getAllFAQs(): FAQItem[] {
  return [
    ...faqDatabase.general,
    ...faqDatabase.comparison,
    ...faqDatabase.technical,
    ...faqDatabase.implementation,
    ...faqDatabase.industry,
  ];
}

